import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { HOOKS } from "../src/lib/hooks.mts";
import { MODS } from "../src/lib/mods.mts";
import { EXIT } from "../src/lib/shared/action.mts";
import { REGISTRY } from "../src/lib/cli/registry.mts";
import { isGroup, listCommands, VERB_NAMES } from "../src/lib/verbs.mts";

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const REFERENCE_DIR = "docs/reference";
export const CLI_PAGE = "cli.md";
export const HOOKS_PAGE = "hooks.md";
export const MODS_PAGE = "mods.md";

const USAGE_LINE = "picket <verb> [args] [--pretty | --human]";
const LEAD_LINE = "Only the lead runs it; the Bash guard denies it to agents.";

const SHARED_FLAGS = [
  ["--root <path>", "run against the project at that path instead of the current one"],
  ["--human", "print text from a verb that prints JSON"],
  ["--json", "print JSON from a verb that prints text"],
  ["--pretty", "indent the JSON"],
  ["picket help <verb>", "print a verb's usage and summary; `picket help` prints every verb"],
];

const EXIT_MEANINGS = {
  done: "the verb did its work",
  failed: "the verb ran and reports a failure, such as a red check",
  refused: 'the verb refused the request: a JSON verb prints `{ "ok": false, "error": ... }`, a text verb prints `refused: <message>` unless you pass `--json`',
  usage: "the arguments are wrong or the verb is unknown",
  crash: "an unexpected error",
};

const HOOK_KINDS =
  "Each hook name starts with its kind. `guard.*` hooks deny a tool call or bounce a turn, `lint.*` and `monitor.*` feed text back to the model, `observe.*` and `emit.*` record what happened, `inject.*` add context when a session or an agent starts, `route.*` applies a verdict and `notify.*` tells the user.";

function generatedLine(source) {
  return `Generated by \`npm run docs\` from ${source}; edit the source, not this page.`;
}

function sentence(summary) {
  const text = summary.charAt(0).toUpperCase() + summary.slice(1);
  return text.endsWith(".") ? text : `${text}.`;
}

function cell(text) {
  return text.replaceAll("|", "\\|");
}

function code(text) {
  return `\`${cell(text)}\``;
}

function fenced(lines) {
  return ["```sh", ...lines, "```"];
}

function page(blocks) {
  return `${blocks.map((block) => block.join("\n")).join("\n\n")}\n`;
}

function commandSection(heading, { summary, usage, leadOnly }) {
  return [heading, "", sentence(summary), ...(leadOnly ? ["", LEAD_LINE] : []), "", ...fenced([`picket ${usage}`])];
}

function groupOf(command) {
  return command.includes(" ") ? command.split(" ")[0] : null;
}

function cliSections(commands) {
  const sections = [];
  let currentGroup = null;
  for (const entry of commands) {
    const group = groupOf(entry.command);
    if (group !== null && group !== currentGroup) sections.push([`## picket ${group}`, "", sentence(entry.groupSummary)]);
    currentGroup = group;
    sections.push(commandSection(`${group === null ? "##" : "###"} picket ${entry.command}`, entry));
  }
  return sections;
}

function exitRows(exit) {
  return Object.entries(exit)
    .sort(([, a], [, b]) => a - b)
    .map(([outcome, value]) => `| ${value} | ${outcome} | ${cell(EXIT_MEANINGS[outcome] ?? outcome)} |`);
}

export function cliPage(commands, exit) {
  return page([
    ["# Command reference", "", generatedLine("`src/lib/verbs.mts` and each verb's `usage`")],
    [`Usage: \`${USAGE_LINE}\`. Each verb prints JSON or text, and the flags below switch it. \`picket --version\` prints the installed version.`],
    ["## Shared flags", "", "| Flag | Does |", "|---|---|", ...SHARED_FLAGS.map(([flag, does]) => `| ${code(flag)} | ${cell(does)} |`)],
    ["## Exit codes", "", "| Code | Outcome | Means |", "|---|---|---|", ...exitRows(exit)],
    ...cliSections(commands),
  ]);
}

function distinct(values) {
  return [...new Set(values)];
}

function hookRow(name, { summary, on }) {
  const events = distinct(on.map(({ event }) => event)).join(", ");
  const matchers = distinct(on.flatMap(({ matcher }) => (matcher === undefined ? [] : [matcher]))).map(code).join(", ");
  return `| ${code(name)} | ${events} | ${matchers} | ${cell(summary)} |`;
}

export function hooksPage(hooks) {
  return page([
    ["# Hooks", "", generatedLine("`src/lib/hooks.mts`")],
    [HOOK_KINDS],
    ["| Hook | Events | Matcher | Does |", "|---|---|---|---|", ...Object.entries(hooks).map(([name, entry]) => hookRow(name, entry))],
  ]);
}

const MODS_INTRO = "The mods ship inside the `picket` plugin and load with it. When `.picket/config.json` sets an off switch to `false`, it turns off its mod, or only the part its row names, from the next session.";

function switchCell(modSwitch) {
  if (modSwitch === null) return "none";
  const off = `${code(modSwitch.key)}: false`;
  return modSwitch.part === null ? off : `${off} turns off ${modSwitch.part} only`;
}

export function modsPage(mods) {
  const rows = Object.entries(mods).map(([name, { summary, switch: modSwitch }]) => `| ${name} | ${switchCell(modSwitch)} | ${cell(summary)} |`);
  return page([["# Mods", "", generatedLine("`src/lib/mods.mts`")], [MODS_INTRO], ["| Mod | Off switch | Does |", "|---|---|---|", ...rows]]);
}

function commandEntry(command, usage) {
  const [name, sub] = command.split(" ");
  const entry = VERB_NAMES[name];
  if (!isGroup(entry)) return { command, summary: entry.summary, usage, leadOnly: entry.leadOnly === true };
  return { command, summary: entry.subverbs[sub].summary, usage, leadOnly: false, groupSummary: entry.summary };
}

async function cliCommands() {
  return Promise.all(listCommands().map(async (command) => commandEntry(command, (await REGISTRY[command]()).verb.usage)));
}

function pagePath(name) {
  return `${REFERENCE_DIR}/${name}`;
}

export async function referencePages() {
  return [
    { path: pagePath(CLI_PAGE), text: cliPage(await cliCommands(), EXIT) },
    { path: pagePath(HOOKS_PAGE), text: hooksPage(HOOKS) },
    { path: pagePath(MODS_PAGE), text: modsPage(MODS) },
  ];
}

export function withLineFeeds(text) {
  return text.replaceAll("\r\n", "\n");
}

function currentText(file) {
  try {
    return withLineFeeds(readFileSync(file, "utf8"));
  } catch {
    return null;
  }
}

export async function writeReferencePages() {
  const written = [];
  for (const { path, text } of await referencePages()) {
    const file = join(REPO, path);
    if (currentText(file) === text) continue;
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, text);
    written.push(path);
  }
  return written;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  writeReferencePages()
    .then((written) => console.log(written.length === 0 ? `${REFERENCE_DIR} is current` : written.join("\n")))
    .catch((err) => {
      console.error(`npm run docs: ${err.message}`);
      process.exitCode = 1;
    });
}

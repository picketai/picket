import { test } from "node:test";
import assert from "node:assert/strict";
import { addedComments, commentLines, extOf, normalise } from "../../dist/lib/shared/comments.mjs";

const lines = (...rows) => rows.join("\n");

test("commentLines finds every comment form, doc comments included", () => {
  const ts = lines("const a = 1; // trailing note", "/// <remarks>Why</remarks>", "/**", " * Totals the lines.", " */", "/* inline block */ const b = 2;");
  assert.deepEqual(commentLines(ts, ".ts"), ["trailing note", "<remarks>Why</remarks>", "Totals the lines.", "inline block"]);
  assert.deepEqual(commentLines(lines("# note", "x = 1  ## banner"), ".py"), ["note", "banner"]);
  assert.deepEqual(commentLines(lines("SELECT 1; -- why", "/* block */"), ".sql"), ["why", "block"]);
  assert.deepEqual(commentLines("Dim a ' basic", ".vb"), ["basic"]);
});

test("block state carries across lines for C-style and markup comments", () => {
  assert.deepEqual(commentLines(lines("/* first", "second", "last */ const a = 1;"), ".js"), ["first", "second", "last"]);
  const html = lines("<div>", "<!-- open", "middle", "-->", "</div>", "<p>x</p><!-- inline -->");
  assert.deepEqual(commentLines(html, ".html"), ["open", "middle", "inline"]);
});

test("Python docstrings count; triple-quoted string values do not", () => {
  const py = lines("def f():", '    """Single line."""', "    '''Multi", "    line'''", '    x = """not a', "    docstring", '    """', "    return x");
  assert.deepEqual(commentLines(py, ".py"), ["Single line.", "Multi", "line"]);
});

test("directives, licence headers, banners and strings are not comments", () => {
  const ts = lines(
    "// eslint-disable-next-line no-console",
    "// SPDX-License-Identifier: MIT",
    "// Copyright 2026 Example Ltd",
    "// <auto-generated />",
    'const s = "// not a comment";',
    "const re = /a\\/\\/b/;",
  );
  assert.deepEqual(commentLines(ts, ".ts"), []);
  assert.deepEqual(commentLines(lines("#!/usr/bin/env python", "# -*- coding: utf-8 -*-", "# noqa: E501"), ".py"), []);
});

test("a line token inside code is not a comment start", () => {
  assert.deepEqual(commentLines(lines("if [ $# -eq 0 ]; then", "n=${#items[@]}", "x=1 # real"), ".sh"), ["real"]);
  assert.deepEqual(commentLines("const a = <a>http://x</a>;", ".tsx"), []);
  assert.deepEqual(commentLines(lines("#!/bin/sh", "# top"), ".sh"), ["top"]);
  assert.deepEqual(commentLines("a();// tight", ".ts"), ["tight"]);
});

test("licence and justification markers exempt only their header and attribute forms", () => {
  assert.deepEqual(commentLines(lines("// Licensed under the Apache License, Version 2.0", "// License: MIT", '[SuppressMessage("x", Justification = "y")]'), ".cs"), []);
  assert.deepEqual(commentLines(lines("// licence check skipped: tariff rounds half up", "// Justification for the cap"), ".ts"), [
    "licence check skipped: tariff rounds half up",
    "Justification for the cap",
  ]);
});

test("craft-lint-allow is not an exemption for the hook", () => {
  assert.deepEqual(commentLines("// craft-lint-allow: CD2 because", ".ts"), ["craft-lint-allow: CD2 because"]);
});

test("unscanned extensions yield nothing", () => {
  for (const ext of [".md", ".json", ".yaml", ".yml", ".toml", ""]) assert.deepEqual(commentLines(lines("# heading", "<!-- note -->", "// x"), ext), [], ext);
  assert.equal(extOf("Dockerfile"), "");
  assert.equal(extOf("src/A.CS"), ".cs");
});

test("normalise strips the token, collapses whitespace and trims", () => {
  assert.equal(normalise("/   half-up:   the tariff\ttable "), "half-up: the tariff table");
  assert.equal(normalise("** doc"), "doc");
  assert.equal(normalise("## banner"), "banner");
});

test("a recorded one-line block comment approval matches the comment it approves", () => {
  const approval = "/** A nested product repo at src/Orders on branch main. */";
  assert.equal(normalise("/** doc */"), "doc");
  assert.deepEqual(addedComments({ ext: ".mjs", before: "", after: approval }), [normalise(approval)]);
});

test("addedComments is a multiset difference, so kept and moved comments never count", () => {
  const before = lines("// keep", "const a = 1;", "// keep", "// moved");
  const after = lines("// moved", "// keep", "const a = 2;", "// keep", "// keep", "// new one");
  assert.deepEqual(addedComments({ ext: ".ts", before, after }), ["keep", "new one"]);
  assert.deepEqual(addedComments({ ext: ".ts", before: "", after: "// a" }), ["a"]);
  assert.deepEqual(addedComments({ ext: ".md", before: "", after: "# heading" }), []);
});

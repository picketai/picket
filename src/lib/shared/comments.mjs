const AFTER_WHITESPACE = /\s/;
const AFTER_STATEMENT = /[\s;)}\]]/;

const AFTER_LABEL = /[\s:]/;

const SLASHES = { token: /\/\//g, after: AFTER_STATEMENT };
const HASH_TOKEN = { token: /#/g, after: AFTER_WHITESPACE };
const C_BLOCK = { open: "/*", close: "*/", stars: true };

const C_STYLE = { lines: [SLASHES], blocks: [C_BLOCK] };
const HASH = { lines: [HASH_TOKEN], blocks: [] };
const PYTHON = { ...HASH, docstring: true };
const RUBY = { lines: [HASH_TOKEN], blocks: [{ open: "=begin", close: "=end", stars: false, lineStart: true }] };
const PERL = { lines: [HASH_TOKEN], blocks: [{ open: "=pod", close: "=cut", stars: false, lineStart: true }] };
const POWERSHELL = { lines: [HASH_TOKEN], blocks: [{ open: "<#", close: "#>", stars: false }] };
const PHP = { lines: [SLASHES, { token: /#(?!\[)/g, after: AFTER_STATEMENT }], blocks: [C_BLOCK] };
const SQL = { lines: [{ token: /--/g, after: AFTER_STATEMENT }], blocks: [C_BLOCK] };
const BASIC = { lines: [{ token: /'/g, after: AFTER_WHITESPACE }, { token: /\bREM(?=\s|$)/gi, after: AFTER_LABEL }], blocks: [] };
export const MARKUP = { lines: [], blocks: [{ open: "<!--", close: "-->", stars: false }] };

const STYLE = { lines: [], blocks: [C_BLOCK] };
const EMBEDDED_REGIONS = [
  { open: /<script\b[^>]*>/i, close: /<\/script\s*>/i, lang: C_STYLE },
  { open: /<style\b[^>]*>/i, close: /<\/style\s*>/i, lang: STYLE },
];
const MARKUP_WITH_SCRIPTS = { ...MARKUP, regions: EMBEDDED_REGIONS };
const RAZOR = { ...MARKUP, blocks: [...MARKUP.blocks, { open: "@*", close: "*@", stars: false }] };

function each(extensions, lang) {
  return Object.fromEntries(extensions.split(" ").map((ext) => [ext, lang]));
}

export const LANGS = {
  ...each(".js .mjs .cjs .jsx .ts .mts .cts .tsx", C_STYLE),
  ...each(".cs .java .kt .kts .go .rs .swift .scala", C_STYLE),
  ...each(".c .h .cpp .hpp .cc .dart .groovy", C_STYLE),
  ".php": PHP,
  ".py": PYTHON,
  ".rb": RUBY,
  ".pl": PERL,
  ".ps1": POWERSHELL,
  ...each(".sh .bash .r", HASH),
  ".sql": SQL,
  ".vb": BASIC,
  ...each(".html .htm .xml .xaml .cshtml .razor .vue .svelte", MARKUP),
};

const DOCUMENT_ROWS = {
  ...each(".html .htm .vue .svelte", MARKUP_WITH_SCRIPTS),
  ...each(".cshtml .razor", RAZOR),
};

function documentRow(ext) {
  return Object.hasOwn(DOCUMENT_ROWS, ext) ? DOCUMENT_ROWS[ext] : Object.hasOwn(LANGS, ext) ? LANGS[ext] : null;
}

export const COMMENT_SUPPRESSION_MARKERS = [
  /eslint-disable/i, /@ts-(ignore|expect-error|nocheck)/i, /biome-ignore/i, /istanbul ignore/i,
  /c8 ignore/i, /\bnoqa\b/i, /pylint:\s*disable/i, /mypy:\s*ignore/i, /type:\s*ignore/i, /nolint/i,
];

export const STATEMENT_SUPPRESSION_MARKERS = [/#pragma warning disable/i, /SuppressMessage/i];

export const SUPPRESSION_MARKERS = [...COMMENT_SUPPRESSION_MARKERS, ...STATEMENT_SUPPRESSION_MARKERS];

export const DIRECTIVE_MARKERS = [
  ...SUPPRESSION_MARKERS, /eslint-enable/i, /prettier-ignore/i, /coverage:/i, /pylint:/i, /mypy:/i, /golangci/i, /#pragma/i,
  /\bJustification\s*=\s*"/, /^\s*(#!|-\*-)/, /^[\s/*#!'-]*(copyright\b|\(c\)\s|©)/i,
  /^[\s/*#!'-]*licen[cs](ed\s+(under|to)\b|e\s*:)/i, /\b(mit|apache|gpl|lgpl|bsd|mpl)\b[\w .-]*\blicen[cs]e\b/i,
  /\bSPDX-/i, /\bautogenerated\b/i, /\bauto-generated\b/i, /\bcode generated\b/i, /<auto-generated/i,
];

export function extOf(path) {
  const i = path.lastIndexOf(".");
  return i < 0 ? "" : path.slice(i).toLowerCase();
}

export function maskStrings(s) {
  const quotesMasked = s.replace(/(["'`])(?:\\.|(?!\1)[^\\])*\1/g, (m) => m[0].repeat(m.length));
  return quotesMasked.replace(
    /(^|[=(,:[!&|?]|\breturn\b)(\s*)\/(?![*/])(?:\\.|\[(?:\\.|[^\]\\])*\]|[^/\n\\])+\/[gimsuyd]*/g,
    (m, pre, ws) => pre + ws + "R".repeat(m.length - pre.length - ws.length),
  );
}

function firstLineToken(masked, { token, after }) {
  for (const match of masked.matchAll(token)) {
    if (match.index === 0 || after.test(masked[match.index - 1])) return { idx: match.index, token: match[0] };
  }
  return null;
}

function blockOpenAt(masked, block) {
  if (block.lineStart) return masked.startsWith(block.open) ? 0 : -1;
  return masked.indexOf(block.open);
}

function earliest(found) {
  return found.filter(Boolean).reduce((first, next) => (first === null || next.idx < first.idx ? next : first), null);
}

function lineComment(text, { idx, token }) {
  const body = text.slice(idx + token.length);
  const isDoc = /^[/!*]/.test(body) || (token === "#" && /^#/.test(body));
  return { body, isDoc, inline: text.slice(0, idx).trim().length > 0, col: idx, closer: null };
}

function blockComment(text, { idx, block: { open, close } }) {
  const rest = text.slice(idx + open.length);
  const end = rest.indexOf(close);
  const body = end < 0 ? rest : rest.slice(0, end);
  return { body, isDoc: /^[*!]/.test(rest), inline: text.slice(0, idx).trim().length > 0, col: idx, closer: end < 0 ? close : null };
}

export function commentOf(text, lang) {
  const masked = maskStrings(text);
  const line = earliest(lang.lines.map((token) => firstLineToken(masked, token)));
  const block = earliest(lang.blocks.map((candidate) => ({ idx: blockOpenAt(masked, candidate), block: candidate })).filter(({ idx }) => idx >= 0));
  if (line && (!block || line.idx < block.idx)) return lineComment(text, line);
  if (block) return blockComment(text, block);
  if (lang.blocks.some(({ stars }) => stars) && /^\s*\*(?!\/)/.test(text)) return { body: text.replace(/^\s*\*/, ""), isDoc: true, inline: false, col: 0, closer: null };
  return null;
}

export function normalise(body) {
  return body.replace(/^[\s/!*#]+/, "").replace(/\s*\*\/\s*$/, "").replace(/\s+/g, " ").trim();
}

function isDirective(text) {
  return DIRECTIVE_MARKERS.some((re) => re.test(text));
}

function tripleQuoteAt(line) {
  const t = line.trimStart();
  return ['"""', "'''"].find((q) => t.startsWith(q)) ?? null;
}

function unclosedTripleQuote(line) {
  return ['"""', "'''"].find((q) => line.split(q).length % 2 === 0) ?? null;
}

function docstringStart(line, quote) {
  const rest = line.trimStart().slice(quote.length);
  const end = rest.indexOf(quote);
  return { body: end < 0 ? rest : rest.slice(0, end), open: end < 0 ? { close: quote, comment: true } : null };
}

function lineStart(line, lang) {
  if (lang.docstring) {
    const leading = tripleQuoteAt(line);
    if (leading) return docstringStart(line, leading);
    const string = unclosedTripleQuote(line);
    if (string) return { body: null, open: { close: string, comment: false } };
  }
  const c = commentOf(line, lang);
  if (!c) return { body: null, open: null };
  const directive = isDirective(c.body) || isDirective(line.slice(c.col));
  return { body: directive ? null : c.body, open: c.closer ? { close: c.closer, comment: true } : null };
}

function blockContinuation(line, open) {
  const end = line.indexOf(open.close);
  const body = open.comment ? (end < 0 ? line : line.slice(0, end)) : null;
  return { body: body !== null && isDirective(body) ? null : body, open: end < 0 ? open : null };
}

function scanned(line, lang, open) {
  return open ? blockContinuation(line, open) : lineStart(line, lang);
}

const MARKUP_COMMENT_SPAN = /<!--[\s\S]*?(?:-->|$)/g;
const OUTSIDE = { open: null, region: null };

function regionOpening(text, regions) {
  const visible = text.replace(MARKUP_COMMENT_SPAN, (span) => " ".repeat(span.length));
  return earliest(regions.map((region) => {
    const opened = region.open.exec(visible);
    return opened && { idx: opened.index, end: opened.index + opened[0].length, region };
  }));
}

function regionPart(text, { region, open }) {
  const close = region.close.exec(text);
  const step = scanned(close ? text.slice(0, close.index) : text, region.lang, open);
  if (!close) return { body: step.body, state: { open: step.open, region }, rest: null };
  return { body: step.body, state: OUTSIDE, rest: text.slice(close.index + close[0].length) };
}

function closedCommentPart(text, open) {
  const step = blockContinuation(text, open);
  if (step.open) return { body: step.body, state: { open: step.open, region: null }, rest: null };
  return { body: step.body, state: OUTSIDE, rest: text.slice(text.indexOf(open.close) + open.close.length) };
}

function markupPart(text, lang, state) {
  if (state.open) return closedCommentPart(text, state.open);
  const opening = regionOpening(text, lang.regions);
  const step = lineStart(opening ? text.slice(0, opening.idx) : text, lang);
  if (!opening) return { body: step.body, state: { open: step.open, region: null }, rest: null };
  return { body: step.body, state: { open: null, region: opening.region }, rest: text.slice(opening.end) };
}

function regionLineBodies(line, lang, state) {
  const bodies = [];
  let part = { state, rest: line };
  while (part.rest !== null) {
    part = part.state.region ? regionPart(part.rest, part.state) : markupPart(part.rest, lang, part.state);
    bodies.push(part.body);
  }
  return { bodies, state: part.state };
}

function lineBodies(line, lang, state) {
  if (lang.regions) return regionLineBodies(line, lang, state);
  const step = scanned(line, lang, state.open);
  return { bodies: [step.body], state: { open: step.open, region: null } };
}

export function commentLines(text, ext) {
  const lang = documentRow(ext);
  if (!lang) return [];
  const bodies = [];
  let state = OUTSIDE;
  for (const line of text.split(/\r?\n/)) {
    const read = lineBodies(line, lang, state);
    state = read.state;
    for (const body of read.bodies.map((found) => (found === null ? "" : normalise(found)))) if (body) bodies.push(body);
  }
  return bodies;
}

export function addedComments({ ext, before = "", after = "" }) {
  const kept = new Map();
  for (const body of commentLines(before, ext)) kept.set(body, (kept.get(body) ?? 0) + 1);
  return commentLines(after, ext).filter((body) => {
    const left = kept.get(body) ?? 0;
    if (left) kept.set(body, left - 1);
    return !left;
  });
}

const C_STYLE = { line: "//", block: { open: "/*", close: "*/", stars: true } };
const HASH = { line: "#", block: null };
const PYTHON = { ...HASH, docstring: true };
const SQL = { line: "--", block: C_STYLE.block };
const BASIC = { line: "'", block: null };
const MARKUP = { line: null, block: { open: "<!--", close: "-->", stars: false } };

function each(extensions, lang) {
  return Object.fromEntries(extensions.split(" ").map((ext) => [ext, lang]));
}

export const LANGS = {
  ...each(".js .mjs .cjs .jsx .ts .mts .cts .tsx", C_STYLE),
  ...each(".cs .java .kt .kts .go .rs .swift .scala", C_STYLE),
  ...each(".c .h .cpp .hpp .cc .php .dart .groovy", C_STYLE),
  ".py": PYTHON,
  ...each(".rb .sh .bash .ps1 .pl .r", HASH),
  ".sql": SQL,
  ".vb": BASIC,
  ...each(".html .htm .xml .xaml .cshtml .razor .vue .svelte", MARKUP),
};

export const DIRECTIVE_MARKERS = [
  /eslint-(disable|enable)/i, /@ts-(ignore|expect-error|nocheck)/i, /prettier-ignore/i,
  /biome-ignore/i, /istanbul ignore/i, /c8 ignore/i, /coverage:/i, /\bnoqa\b/i, /pylint:/i,
  /mypy:/i, /type:\s*ignore/i, /nolint/i, /golangci/i, /#pragma/i, /SuppressMessage/i,
  /Justification/i, /^\s*(#!|-\*-)/, /\bcopyright\b/i, /\blicen[cs]e\b/i,
  /\bSPDX-/i, /\bautogenerated\b/i, /\bauto-generated\b/i, /\bcode generated\b/i, /<auto-generated/i,
];

export function extOf(path) {
  const i = path.lastIndexOf(".");
  return i < 0 ? "" : path.slice(i).toLowerCase();
}

export function maskStrings(s) {
  const quotesMasked = s.replace(/(["'`])(?:\\.|(?!\1)[^\\])*\1/g, (m) => m[0].repeat(m.length));
  return quotesMasked.replace(
    /(^|[=(,:[!&|?]|\breturn\b)(\s*)\/(?![*/])(?:\\.|\[(?:\\.|[^\]\\])*\]|[^/\n\\])+\/[gimsuyd]*/g,
    (m, pre, ws) => pre + ws + "R".repeat(m.length - pre.length - ws.length),
  );
}

export function commentOf(text, lang) {
  const masked = maskStrings(text);
  const idx = lang.line ? masked.indexOf(lang.line) : -1;
  if (idx >= 0) {
    const before = text.slice(0, idx).trim();
    const body = text.slice(idx + lang.line.length);
    const isDoc = /^[/!*]/.test(body) || (lang.line === "#" && /^#/.test(body));
    return { body, isDoc, inline: before.length > 0, col: idx, closer: null };
  }
  if (!lang.block) return null;
  const { open, close, stars } = lang.block;
  const b = masked.indexOf(open);
  if (b >= 0) {
    const rest = text.slice(b + open.length);
    const end = rest.indexOf(close);
    const body = end < 0 ? rest : rest.slice(0, end);
    return { body, isDoc: /^[*!]/.test(rest), inline: text.slice(0, b).trim().length > 0, col: b, closer: end < 0 ? close : null };
  }
  if (stars && /^\s*\*(?!\/)/.test(text)) return { body: text.replace(/^\s*\*/, ""), isDoc: true, inline: false, col: 0, closer: null };
  return null;
}

export function normalise(body) {
  return body.replace(/^[\s/!*#]+/, "").replace(/\s+/g, " ").trim();
}

function isDirective(text) {
  return DIRECTIVE_MARKERS.some((re) => re.test(text));
}

function tripleQuoteAt(line) {
  const t = line.trimStart();
  return ['"""', "'''"].find((q) => t.startsWith(q)) ?? null;
}

function unclosedTripleQuote(line) {
  return ['"""', "'''"].find((q) => line.split(q).length % 2 === 0) ?? null;
}

function docstringStart(line, quote) {
  const rest = line.trimStart().slice(quote.length);
  const end = rest.indexOf(quote);
  return { body: end < 0 ? rest : rest.slice(0, end), open: end < 0 ? { close: quote, comment: true } : null };
}

function lineStart(line, lang) {
  if (lang.docstring) {
    const leading = tripleQuoteAt(line);
    if (leading) return docstringStart(line, leading);
    const string = unclosedTripleQuote(line);
    if (string) return { body: null, open: { close: string, comment: false } };
  }
  const c = commentOf(line, lang);
  if (!c) return { body: null, open: null };
  const directive = isDirective(c.body) || isDirective(line.slice(c.col));
  return { body: directive ? null : c.body, open: c.closer ? { close: c.closer, comment: true } : null };
}

function blockContinuation(line, open) {
  const end = line.indexOf(open.close);
  const body = open.comment ? (end < 0 ? line : line.slice(0, end)) : null;
  return { body: body !== null && isDirective(body) ? null : body, open: end < 0 ? open : null };
}

export function commentLines(text, ext) {
  const lang = LANGS[ext];
  if (!lang) return [];
  const bodies = [];
  let open = null;
  for (const line of text.split(/\r?\n/)) {
    const step = open ? blockContinuation(line, open) : lineStart(line, lang);
    open = step.open;
    const body = step.body === null ? "" : normalise(step.body);
    if (body) bodies.push(body);
  }
  return bodies;
}

export function addedComments({ ext, before = "", after = "" }) {
  const kept = new Map();
  for (const body of commentLines(before, ext)) kept.set(body, (kept.get(body) ?? 0) + 1);
  return commentLines(after, ext).filter((body) => {
    const left = kept.get(body) ?? 0;
    if (left) kept.set(body, left - 1);
    return !left;
  });
}
